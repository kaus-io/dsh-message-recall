/**
 * Build the TypeScript sources into the exact artifacts the DSH profile loads.
 *
 * `client.js` must be a CJS-shaped bundle wrapped in the browser module
 * loader's factory: React comes from the host module table and the package id
 * is the module id. `index.js` is the Host half (plain ESM). With `--check`
 * nothing is written: the committed artifacts must match a fresh build.
 */
import { build } from 'esbuild'
import type { BuildResult } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

/** 一个需要提交的生成产物。 / One committed generated artifact. */
interface Artifact {
  readonly file: string
  readonly text: string
}

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8')) as { name: string; version: string }
const check = process.argv.includes('--check')

const clientBuild = await build({
  entryPoints: [join(root, 'src/client.tsx')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  jsx: 'automatic',
  external: ['react', 'react/jsx-runtime'],
  legalComments: 'none',
  banner: {
    js: `// Message Recall ${pkg.version}. Generated by scripts/build.mjs; edit src/.\nwindow.__ModuleLoader__.load({ id: ${JSON.stringify(pkg.name)}, factory: (require) => { const module = { exports: {} }; const exports = module.exports;`,
  },
  footer: { js: 'return module.exports; } });' },
})

const hostBuild = await build({
  entryPoints: [join(root, 'src/host.ts')],
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'node',
  target: 'node20',
  legalComments: 'none',
})

/** 读取 esbuild 的内存输出；`write: false` 必然有 outputFiles。 / Read the in-memory output of a `write: false` build. */
function outputText(result: BuildResult, file: string): string {
  const text = result.outputFiles?.[0]?.text
  if (text === undefined) throw new Error(`esbuild produced no output for ${file}`)
  return text
}

const artifacts: Artifact[] = [
  { file: 'client.js', text: outputText(clientBuild, 'client.js') },
  { file: 'index.js', text: outputText(hostBuild, 'index.js') },
]

if (check) {
  for (const artifact of artifacts) {
    const current = await readFile(join(root, artifact.file), 'utf8')
    if (current !== artifact.text) {
      throw new Error(`${artifact.file} is stale; run node scripts/build.mjs`)
    }
  }
  console.log(`client artifacts are current: ${pkg.name}@${pkg.version}`)
} else {
  for (const artifact of artifacts) await writeFile(join(root, artifact.file), artifact.text, 'utf8')
  console.log(`built ${pkg.name}@${pkg.version}: client.js, index.js`)
}
